def weekly(i, name, cadence, schedule, venue, hood, address, organizer, admission,
           src, season, unverified, notes=""):
    return {
        "id": f"w-{i:03d}", "name": name, "category": "monthly" if "month" in cadence.lower() else "weekly",
        "cadence": cadence, "schedule": schedule, "venue": venue, "neighborhood": hood,
        "address": address, "organizer": organizer, "admission": admission,
        "season": season, "source_url": SOURCES[src][0], "source_title": SOURCES[src][1],
        "source_type": SOURCES[src][2], "verified_on": VERIFIED_ON,
        "unverified_fields": unverified, "notes": notes,
    }


