def main():
    data_dir = os.path.join(ROOT, "data")
    os.makedirs(data_dir, exist_ok=True)
    with open(os.path.join(data_dir, "weekly.json"), "w") as fh:
        json.dump({"category": "weekly+monthly", "verified_on": VERIFIED_ON, "events": WEEKLY}, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    with open(os.path.join(data_dir, "annual.json"), "w") as fh:
        json.dump({"category": "annual", "verified_on": VERIFIED_ON, "events": ANNUAL}, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    with open(os.path.join(data_dir, "special.json"), "w") as fh:
        json.dump({"category": "special", "verified_on": VERIFIED_ON, "events": SPECIAL}, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    with open(os.path.join(data_dir, "flagged.json"), "w") as fh:
        json.dump({"verified_on": VERIFIED_ON, "items": FLAGGED}, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    sources = []
    for key, (url, title, typ) in SOURCES.items():
        sources.append({"key": key, "url": url, "title": title, "type": typ, "accessed": VERIFIED_ON})
    with open(os.path.join(data_dir, "sources.json"), "w") as fh:
        json.dump({"verified_on": VERIFIED_ON, "sources": sources}, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    print(f"weekly={len(WEEKLY)} annual={len(ANNUAL)} special={len(SPECIAL)} flagged={len(FLAGGED)} sources={len(SOURCES)}")


if __name__ == "__main__":
    main()
